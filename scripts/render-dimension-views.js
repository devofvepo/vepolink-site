const fs = require("fs");
const path = require("path");

// Derive independent elevations from the complete drawings without redrawing
// the instruments. Re-run after changing one of the source SVGs.
const drawings = [
  ["ambient-co", "Ambient CO analyzer", [20, 10, 480, 280], [540, 10, 430, 280]],
  ["ambient-co2", "Ambient CO2 analyzer", [20, 10, 480, 280], [540, 10, 430, 280]],
  ["ambient-nox", "Ambient NOx analyzer", [20, 10, 480, 280], [540, 10, 430, 280]],
  ["ambient-ozone", "Ambient ozone analyzer", [20, 10, 480, 280], [540, 10, 430, 280]],
  ["ambient-btex", "Ambient BTEX analyzer", [20, 10, 480, 280], [540, 10, 430, 280]],
  ["ambient-so2", "Ambient SO2 analyzer", [132, -10, 360, 182], [512, -10, 360, 182]],
  ["fixed-gas-detector", "Fixed gas detector", [-14, -14, 286, 350], [304, -14, 154, 350]],
  ["portable-multi-gas-detector", "Portable multi gas detector", [-14, -14, 184, 194], [176, -14, 60, 194]],
  ["portable-single-gas-detector", "Portable single gas detector", [-14, -14, 184, 194], [176, -14, 60, 194]],
  ["sensor-based-air-monitor", "Ambient air monitor", [244, -14, 280, 278], [518, -14, 148, 278]],
];
const directory = path.resolve(__dirname, "../assets/products");

for (const [name, title, front, side] of drawings) {
  const source = fs.readFileSync(path.join(directory, `${name}-dimensions.svg`), "utf8");
  for (const [view, bounds] of [["front", front], ["side", side]]) {
    const svg = source
      .replace(/<svg\b[^>]*>/, (root) => root
        .replace(/\bwidth="[^"]*"/, `width="${bounds[2]}"`)
        .replace(/\bheight="[^"]*"/, `height="${bounds[3]}"`)
        .replace(/\bviewBox="[^"]*"/, `viewBox="${bounds.join(" ")}"`))
      .replace(/(<title\b[^>]*>)[\s\S]*?(<\/title>)/, `$1${title}: ${view} elevation$2`)
      .replace(/(<desc\b[^>]*>)[\s\S]*?(<\/desc>)/, `$1${view === "front" ? "Front" : "Side"} elevation from the complete instrument dimension drawing.$2`);
    fs.writeFileSync(path.join(directory, `${name}-dimensions-${view}.svg`), `<!-- Generated by scripts/render-dimension-views.js. -->\n${svg}`);
  }
}
